import { describe, expect, it } from 'vitest'

import { extractMarkdownHeadings } from './markdown'

describe('extractMarkdownHeadings', () => {
  it('matches the heading IDs generated by rehype-slug', () => {
    const headings = extractMarkdownHeadings(
      [
        '# Story title',
        '',
        '## Same heading',
        '',
        '```md',
        '## Not a heading',
        '```',
        '',
        '## Same heading',
        '',
        '### A **formatted** detail',
        '',
        '#### Too deep',
      ].join('\n'),
    )

    expect(headings).toEqual([
      { id: 'same-heading', text: 'Same heading', level: 2 },
      { id: 'same-heading-1', text: 'Same heading', level: 2 },
      { id: 'a-formatted-detail', text: 'A formatted detail', level: 3 },
    ])
  })
})
