import GithubSlugger from 'github-slugger'

export interface MarkdownHeading {
  id: string
  text: string
  level: number
}

const FENCE_PATTERN = /^\s*(```|~~~)/
const HEADING_PATTERN = /^(#{1,6})\s+(.+?)\s*#*\s*$/

function stripInlineMarkdown(value: string): string {
  return value
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/[*_~]+/g, '')
    .replace(/\\([\\`*_{}[\]()#+\-.!>])/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * Extract ATX headings outside fenced code blocks. The slugger matches the IDs
 * generated by rehype-slug so the table of contents links to the rendered
 * headings, including duplicate-heading suffixes.
 */
export function extractMarkdownHeadings(
  markdown: string,
  minLevel = 2,
  maxLevel = 3,
): MarkdownHeading[] {
  const slugger = new GithubSlugger()
  const headings: MarkdownHeading[] = []
  let inFence = false

  for (const line of markdown.split(/\r?\n/)) {
    if (FENCE_PATTERN.test(line)) {
      inFence = !inFence
      continue
    }
    if (inFence) {
      continue
    }

    const match = HEADING_PATTERN.exec(line)
    if (!match) {
      continue
    }

    const level = match[1].length
    const text = stripInlineMarkdown(match[2])
    if (!text) {
      continue
    }

    // Consume the slug even for headings outside the requested range so
    // duplicate suffixes remain aligned with rehype-slug.
    const id = slugger.slug(text)
    if (level >= minLevel && level <= maxLevel) {
      headings.push({ id, text, level })
    }
  }

  return headings
}

export function stripMarkdown(value: string): string {
  return value
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/~~~[\s\S]*?~~~/g, ' ')
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    .replace(/^\s{0,3}>\s?/gm, '')
    .replace(/^\s{0,3}(?:[-*+]|\d+\.)\s+/gm, '')
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/[*_~]+/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}
